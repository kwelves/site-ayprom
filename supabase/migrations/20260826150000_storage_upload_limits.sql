-- QA-012 (вторая половина): три из четырёх хранилищ принимали файл любого типа
-- и любого размера. Ограничения существовали только в коде приложения — и то
-- лишь для фотографий товара; логотипы брендов и картинки категорий не
-- проверялись вообще.
--
-- Здесь ограничения закрепляются на самих хранилищах: даже если проверка в
-- приложении будет обойдена или изменена, Storage откажет сам. Это тот же
-- принцип, что и у CHECK-констрейнтов для масштаба в фазе 2 — последний рубеж
-- не должен зависеть от прикладного слоя.
--
-- Значения выбраны по фактическим данным каталога, а не назначены произвольно:
-- самый крупный существующий файл — 299 КБ (фото товара), логотипы — около
-- 3 КБ. Лимит 8 МБ повторяет действующий контракт приложения и оставляет более
-- чем двадцатикратный запас.
--
-- `site-media` намеренно не трогается: у него уже настроены 40 МБ и video/mp4.
-- Он и служит образцом того, как должны были выглядеть остальные.

UPDATE "storage"."buckets"
SET
  "file_size_limit" = 8388608,
  "allowed_mime_types" = ARRAY['image/jpeg', 'image/png', 'image/webp', 'image/avif']
WHERE "id" IN ('product-images', 'category-images');

-- Логотипы дополнительно принимают вектор: PROJECT_BRIEF прямо требует
-- сохранять SVG векторным. Содержимое обезвреживается на сервере до записи
-- (src/lib/admin/upload-validation.ts) — ограничение типа здесь лишь закрывает
-- путь в обход приложения.
UPDATE "storage"."buckets"
SET
  "file_size_limit" = 8388608,
  "allowed_mime_types" = ARRAY['image/svg+xml', 'image/jpeg', 'image/png', 'image/webp', 'image/avif']
WHERE "id" = 'brand-logos';
