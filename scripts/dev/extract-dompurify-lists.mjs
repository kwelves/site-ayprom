// Reads the SVG allow lists of the installed DOMPurify and (with --write) stores them for the
// Worker-compatible SVG sanitizer. A unit test compares the stored copy with the installed library,
// so an upgrade of DOMPurify that changes the lists is noticed instead of silently ignored.
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync("node_modules/dompurify/dist/purify.es.mjs", "utf8");
const lists = {};
for (const match of source.matchAll(/const ([A-Za-z0-9$_]+) = freeze\(\[([\s\S]*?)\]\);/g)) {
  lists[match[1]] = [...match[2].matchAll(/'([^']+)'/g)].map((entry) => entry[1]);
}

const picked = {
  svgElements: lists["svg$1"],
  svgFilterElements: lists.svgFilters,
  svgDisallowedElements: lists.svgDisallowed,
  svgAttributes: lists.svg,
  xmlAttributes: lists.xml,
};
for (const [name, values] of Object.entries(picked)) {
  if (!values?.length) throw new Error(`DOMPurify list not found: ${name}`);
}

if (process.argv.includes("--write")) {
  const lines = ["// Generated by scripts/dev/extract-dompurify-lists.mjs from the installed DOMPurify. Do not edit by hand.", ""];
  for (const [name, values] of Object.entries(picked)) {
    lines.push(`export const ${name}: readonly string[] = ${JSON.stringify(values)};`, "");
  }
  writeFileSync("src/cloudflare/admin-worker/svg/dompurify-lists.ts", lines.join("\n"));
  console.log("written");
} else {
  console.log(JSON.stringify(picked));
}
