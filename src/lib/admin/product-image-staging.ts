// QA-004: параметры промежуточной загрузки фотографий товара.
//
// Вынесены в отдельный модуль, чтобы одни и те же значения использовали
// серверные действия, задание уборки и тесты — расхождение между ними означало
// бы либо преждевременное удаление работы администратора, либо накопление
// мусора.

export const PRODUCT_IMAGE_STAGING_BUCKET = "product-image-staging";

/**
 * Сколько живёт недогруженное, прежде чем попасть под уборку.
 *
 * Сутки: администратор может начать заводить товар, уйти и вернуться на
 * следующий день — загруженные фотографии должны его дождаться. Меньший срок
 * означал бы потерю уже сделанной работы.
 */
export const STAGING_RETENTION_SECONDS = 24 * 60 * 60;

/**
 * Сколько действует сама ссылка на загрузку.
 *
 * Пять минут — с запасом на 8 МБ по медленному каналу, но недостаточно, чтобы
 * утёкшая ссылка оставалась полезной. Это разные сроки: ссылка короткая,
 * хранение длинное.
 */
export const UPLOAD_URL_TTL_SECONDS = 5 * 60;

/** Как часто имеет смысл запускать уборку. Используется в настройке расписания. */
export const CLEANUP_BATCH_LIMIT = 100;

/**
 * Путь файла в промежуточном хранилище.
 *
 * Строится только из значений, выданных сервером: идентификатора сессии,
 * идентификатора файла и расширения, выведенного из проверенного типа. Имя
 * файла, присланное браузером, в путь не попадает — иначе клиент управлял бы
 * тем, куда и подо что записывается объект.
 */
export function buildStagingObjectPath(draftId: string, fileId: string, extension: string): string {
  if (!isUuid(draftId)) throw new Error("Некорректный идентификатор сессии загрузки.");
  if (!isUuid(fileId)) throw new Error("Некорректный идентификатор файла.");
  if (!/^[a-z0-9]{2,5}$/.test(extension)) throw new Error("Некорректное расширение файла.");
  return `${draftId}/${fileId}.${extension}`;
}

export function isUuid(value: string): boolean {
  return /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(value);
}

/**
 * Извлекает идентификатор сессии из пути.
 *
 * Нужна уборке и отмене: они получают путь из базы и должны убедиться, что он
 * принадлежит ожидаемой сессии, а не построен вручную.
 */
export function draftIdFromStagingPath(objectPath: string): string | null {
  const [draftId, rest] = objectPath.split("/");
  if (!rest || !isUuid(draftId)) return null;
  return draftId;
}

/** Каноническое расширение по проверенному типу — единый источник для всех путей загрузки. */
export const CANONICAL_UPLOAD_EXTENSION: Record<string, string | undefined> = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
  "image/avif": "avif",
};
