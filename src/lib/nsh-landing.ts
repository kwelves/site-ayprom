export const NSH_HUB_PATH = "/nsh-nasos";

export interface NshFaqItem {
  question: string;
  answer: string;
}

export interface NshLandingPage {
  path: string;
  /** Короткая подпись для хлебных крошек и ссылок на другие страницы. */
  crumb: string;
  /** `<title>` страницы без «AYPROM»: шаблон сайта сам добавит « — AYPROM». */
  title: string;
  /** `<meta name="description">`, до 160 знаков. */
  description: string;
  h1: string;
  eyebrow: string;
  intro: string[];
  /** Блок «Как это работает на этой технике». */
  usage: { heading: string; paragraphs: string[] };
  faq: NshFaqItem[];
  /** Страница каталога по типу техники, если она есть: туда ведёт ссылка «Вся совместимая техника». */
  vehicleTypeSlug?: string;
}

