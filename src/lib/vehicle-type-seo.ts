// Тексты страниц «по типу техники». Живут в коде, а не в базе: таблица
// vehicle_types хранит только slug, name и порядок, отдельных полей под
// описание там нет. Типов пять и меняются они редко, поэтому колонки в базе
// и форма в админке пока не окупаются — если тексты начнут править часто,
// это первый кандидат на перенос в Supabase.
//
// Записи может не быть: тогда страница ведёт себя ровно как раньше —
// заголовок из названия типа и общий шаблон описания.
